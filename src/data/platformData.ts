// Centralized data store for the MLOps platform
// This ensures perfect coherence between all modules

export interface TeamMember {
  id: string;
  initials: string;
  name: string;
  role: string;
  email: string;
  avatar?: string;
}

export interface Dataset {
  id: string;
  name: string;
  type: "Table" | "Dataset" | "Stream" | "File";
  schema: string;
  classification: "Public" | "Sensitive" | "Regulated" | "Restricted";
  pii: boolean;
  owner: string;
  ownerId: string;
  projectId: string;
  records: string;
  size: string;
  quality: number;
  lastUpdated: string;
  createdAt: string;
  description: string;
  tags: string[];
  version: string;
  storageLocation: string;
  format: string;
  lineage: {
    sources: string[];
    transformations: string[];
    consumers: string[];
  };
}

export interface Pipeline {
  id: string;
  name: string;
  projectId: string;
  type: "Training" | "ETL" | "Feature" | "Inference" | "Monitoring";
  status: "active" | "paused" | "failed" | "completed";
  schedule: string;
  lastRun: string;
  nextRun: string;
  duration: string;
  steps: {
    name: string;
    type: string;
    status: string;
    duration: string;
  }[];
  inputDatasets: string[];
  outputDatasets: string[];
  models: string[];
  resources: {
    cpu: string;
    memory: string;
    gpu: string;
  };
  version: string;
  tool: string;
  toolVersion: string;
}

export interface Experiment {
  id: string;
  name: string;
  projectId: string;
  modelId?: string;
  status: "running" | "completed" | "failed" | "queued";
  accuracy: number | null;
  loss: number | null;
  f1Score: number | null;
  duration: string;
  createdAt: string;
  author: string;
  authorId: string;
  epochs: number;
  learningRate: number | null;
  datasetId: string;
  hyperparameters: Record<string, any>;
  metrics: Record<string, number>;
  artifacts: string[];
}

export interface Model {
  id: string;
  name: string;
  projectId: string;
  description: string;
  stage: "Production" | "Staging" | "Development" | "Archived";
  latestVersion: string;
  versions: number;
  accuracy: string;
  latency: string;
  requests: string;
  lastUpdated: string;
  createdAt: string;
  framework: string;
  algorithm: string;
  author: string;
  authorId: string;
  deployments: number;
  datasetIds: string[];
  experimentIds: string[];
  pipelineIds: string[];
  endpoints: {
    id: string;
    name: string;
    region: string;
    status: string;
    traffic: string;
    latency: string;
    requests: string;
  }[];
  resources: {
    cpu: string;
    memory: string;
    gpu: string;
    storage: string;
  };
  metadata: {
    inputSchema: string;
    outputSchema: string;
    dependencies: string[];
    license: string;
  };
}

export interface Deployment {
  id: string;
  name: string;
  modelId: string;
  projectId: string;
  environment: "production" | "staging" | "development";
  status: "healthy" | "degraded" | "failed" | "deploying";
  version: string;
  replicas: number;
  traffic: string;
  latency: string;
  requests: string;
  region: string;
  createdAt: string;
  updatedAt: string;
  resources: {
    cpu: string;
    memory: string;
    gpu: string;
  };
  scaling: {
    min: number;
    max: number;
    current: number;
  };
}

export interface Project {
  id: string;
  name: string;
  description: string;
  status: "active" | "paused" | "completed" | "archived";
  starred: boolean;
  gitRepo: string;
  gitBranch: string;
  createdAt: string;
  lastActivity: string;
  progress: number;
  team: TeamMember[];
  modelIds: string[];
  experimentIds: string[];
  datasetIds: string[];
  pipelineIds: string[];
  deploymentIds: string[];
  resources: {
    totalCpu: string;
    totalMemory: string;
    totalGpu: string;
    totalStorage: string;
    monthlyCost: number;
    carbonEmissions: number;
  };
  tags: string[];
}

