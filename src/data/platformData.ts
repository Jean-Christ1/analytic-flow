// Helper functions for data access
export const getProjectById = (id: string): Project | undefined => 
  projects.find(p => p.id === id);

export const getModelById = (id: string): Model | undefined => 
  models.find(m => m.id === id);

export const getExperimentById = (id: string): Experiment | undefined => 
  experiments.find(e => e.id === id);

export const getDatasetById = (id: string): Dataset | undefined => 
  datasets.find(d => d.id === id);

export const getPipelineById = (id: string): Pipeline | undefined => 
  pipelines.find(p => p.id === id);

export const getDeploymentById = (id: string): Deployment | undefined => 
  deployments.find(d => d.id === id);

export const getModelsByProject = (projectId: string): Model[] => 
  models.filter(m => m.projectId === projectId);

export const getExperimentsByProject = (projectId: string): Experiment[] => 
  experiments.filter(e => e.projectId === projectId);

export const getDatasetsByProject = (projectId: string): Dataset[] => 
  datasets.filter(d => d.projectId === projectId);

export const getPipelinesByProject = (projectId: string): Pipeline[] => 
  pipelines.filter(p => p.projectId === projectId);

export const getDeploymentsByProject = (projectId: string): Deployment[] => 
  deployments.filter(d => d.projectId === projectId);

export const getDeploymentsByModel = (modelId: string): Deployment[] => 
  deployments.filter(d => d.modelId === modelId);

export const getExperimentsByModel = (modelId: string): Experiment[] => 
  experiments.filter(e => e.modelId === modelId);
